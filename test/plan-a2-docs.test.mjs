// Round 270 (Rodrigo: «vamos avançar com o a-2»; D138 part 2, AUDIT-4 §5 A-2): the plan of A-2 is written down before any code: docs/plan-a2-pins.md, ROADMAP D144 and
// milestone M21 (C21.1, C21.2). Written before the docs; red until they exist. Docs only: no source, nothing pinned touched, the pin does not move.
// The plan rests on one experiment (§2), run on a copy: a one-line comment appended to a pinned file, `bump-round --refresh`, `npm run test:fast`. The test holds that the
// plan records it and says what it found, so a later reader does not have to trust the prose.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { statusText, statusWithArchives } from './status-text.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (f) => readFileSync(join(root, f), 'utf8');
const PLAN = 'docs/plan-a2-pins.md';
const CARDS = ['C21.1', 'C21.2'];
const planBlocks = () => read(PLAN).split('## 5. Plan, one round per card')[1].split('## 6.')[0].split(/^### /m).slice(1);

test('the plan exists and has its sections', () => {
  assert.ok(existsSync(join(root, PLAN)), `${PLAN} missing`);
  const p = read(PLAN);
  for (const h of ['## 1. What A-2 asks', '## 2. What an edit of a pinned file costs today (measured)', '## 3. The two halves of A-2, read against the tree', '## 4. What stays out of A-2', '## 5. Plan, one round per card', '## 6. Open decisions']) assert.ok(p.includes(h), `section «${h}» missing`);
});

test('§2 records the experiment: one comment line in a pinned file, bump-round --refresh, the fast suite, and what turned red (the four `pinned-*-move` tests that freeze bytes)', () => {
  const p = read(PLAN).split('## 2. What an edit of a pinned file costs today (measured)')[1].split('## 3.')[0];
  for (const k of ['bump-round', 'test:fast', 'policy.mjs', 'pinned-policy-move', 'pinned-baseline-move', 'pinned-manifest-move', 'pinned-recovery-report-move', 'zipkit', 'sha256']) assert.ok(p.includes(k), `«${k}» missing in §2`);
  assert.match(p, /1580/, 'the size of the fast suite of the experiment');
  assert.match(p, /1 (test )?red|one test red|1 of 1580/i, 'the number of red tests is not recorded');
});

test('§3 answers both halves: the pin is already generated by bump-round and lives only in CLAUDE.md; fewer modules is rejected, with the reason', () => {
  const p = read(PLAN).split('## 3. The two halves of A-2, read against the tree')[1].split('## 4.')[0];
  assert.match(p, /already/i);
  assert.match(p, /CLAUDE\.md/);
  assert.match(p, /bump-round/);
  assert.match(p, /fewer modules|merge/i);
  assert.match(p, /reject/i);
  assert.match(p, /D7/);
});

test('§4 names what stays out: the pin value and the start line of item 17, RECOVER/ and its five names, zipkit (no narrower reader), and the real-dump gate', () => {
  const p = read(PLAN).split('## 4. What stays out of A-2')[1].split('## 5.')[0];
  for (const k of ['RECOVER/', 'item 17', 'zipkit', 'recovery-report', 'emergency-dump']) assert.ok(p.includes(k), `«${k}» missing in §4`);
  assert.match(p, /G-C11|\/dump/);
});

test('the plan has one block per card; each says its source files (at most 3), tests first, the pin, and done-when; none moves the pin', () => {
  const blocks = planBlocks();
  assert.equal(blocks.length, CARDS.length);
  CARDS.forEach((c, i) => assert.ok(blocks[i].startsWith(c + ' '), `block ${i + 1} should be ${c}, is «${blocks[i].slice(0, 12)}»`));
  for (const b of blocks) {
    for (const k of ['Source files:', 'Tests first:', 'Pin:', 'Done when:']) assert.ok(b.includes(k), `«${k}» missing in «${b.slice(0, 12)}»`);
    const src = b.split('\n').find((l) => l.includes('Source files:'));
    assert.ok((src.match(/\.mjs/g) ?? []).length <= 3, `more than 3 source files in «${b.slice(0, 12)}»`);
    assert.match(b.split('\n').find((l) => l.includes('Pin:')), /does not move/i, `the pin must not move in «${b.slice(0, 12)}»`);
  }
});

test('§6 lists the open decisions D-270a to D-270d, each with a suggestion', () => {
  const p = read(PLAN).split('## 6. Open decisions')[1];
  for (const d of ['D-270a', 'D-270b', 'D-270c', 'D-270d']) assert.ok(p.includes(d), `${d} missing`);
  assert.ok((p.match(/Claude suggests/g) ?? []).length >= 4, 'each decision needs «Claude suggests»');
});

test('ROADMAP: D138 says A-2 is now planned (the old «A-2 waits» stays as history); D144 exists; M21 has the two cards; docs/README lists the plan', () => {
  const r = read('ROADMAP.md');
  const d138 = r.split('\n').find((l) => l.startsWith('| D138 |'));
  assert.match(d138, /A-2 waits/, 'the round 242 history is kept');
  assert.match(d138, /round 270/i);
  assert.match(d138, /plan-a2-pins/);
  assert.match(r, /^\| D144 \|/m);
  assert.match(r, /^### M21 /m);
  for (const c of CARDS) assert.match(r, new RegExp(`^\\| ${c.replace('.', '\\.')} \\|`, 'm'), `${c} row missing`);
  assert.ok(read('docs/README.md').includes('plan-a2-pins.md'), 'docs/README.md does not list the plan');
});

test('the status file (the newest one) names the plan, D144 and C21.1, and says what Rodrigo has to confirm', () => {
  const s = statusWithArchives(), live = statusText(); // names: file + archives (C19.3); the Next up block: the live file
  assert.ok(s.includes('plan-a2-pins') && s.includes('D144') && s.includes('C21.1'));
  assert.match(live.split('## Next up')[1].split('## Gates')[0], /D-270a/);
});
